#!/usr/bin/env python3
"""Render Drafted interface allocation from IF -> LLR -> SR and TC references."""
import argparse
from pathlib import Path
import re
import tomllib


def references(value):
    return value if isinstance(value, list) else re.findall(r"(?:LLR|SR|TC|IF|B)-\d+", value or "")


def render(root):
    def read(path, table):
        return tomllib.loads((root / path).read_text(encoding="utf-8"))[table]
    interfaces = read("docs/requirements/interfaces.toml", "interface")
    llrs = read("docs/requirements/low-level-requirements.toml", "design")
    srs = read("docs/requirements/system-requirements.toml", "requirement")
    cases = read("docs/test/test-cases.toml", "test")
    frame = read("docs/requirements/external.toml", "boundary")
    lines = [
        "# Interface trace map", "",
        "Generated by `python scripts/gen_interface_map.py` from the live registries.",
        "Drafted coverage is allocation, not proof of implementation.",
        "IF-001 is preserved legacy context and is not revalidated by this map.", "",
        "| Interface | Owner | Design links | Derived accepted SRs | Planned verification cases |",
        "|---|---|---|---|---|",
    ]
    for iid, row in interfaces.items():
        designs = [v for v in references(row.get("verified_by")) if v in llrs]
        parents = sorted({v for d in designs for v in references(llrs[d].get("sr_refs")) if v in srs})
        tests = sorted(k for k, v in cases.items() if iid in references(v.get("verifies")))
        lines.append(f"| {iid} | {row['owner']} | {', '.join(designs)} | {', '.join(parents)} | {', '.join(tests) or 'Legacy binding not revalidated'} |")
    lines += ["", "## Boundary coverage", "", "| Approved crossing | Draft realizing interfaces |", "|---|---|"]
    for bid, row in frame.items():
        if row["status"] != "Approved":
            continue
        hits = [iid for iid, v in interfaces.items() if bid in references(v.get("interface_from_external")) + references(v.get("interface_to_external"))]
        gap = "Conditional B-11: automatic provisioning not offered; local guidance only" if bid == "B-11" else "UNALLOCATED"
        lines.append(f"| {bid} | {', '.join(hits) or gap} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = root / "docs/interfaces/trace-map.md"
    expected = render(root)
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Interface trace map is stale; run scripts/gen_interface_map.py")
        print("Interface trace map is current.")
    else:
        output.write_text(expected, encoding="utf-8")
        print("Wrote docs/interfaces/trace-map.md")


if __name__ == "__main__":
    main()
